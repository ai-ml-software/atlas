/**
 * Arabic for the Academy LMS interface.
 *
 * The public academy site keeps its Arabic in the ha_*_translation tables.
 * This is the other half of the application: the admin panel and the Academy
 * LMS front end, both of which read their text through get_phrase() and
 * site_phrase() from the `language` table. Keys here are the normalised form
 * those helpers look up, which is the English string lowercased with spaces
 * turned into underscores.
 *
 * Two conventions, because an LMS read by hotel staff is not a place to be
 * clever with language:
 *
 *  - Modern Standard Arabic throughout. It is what every Arabic reader in the
 *    Gulf shares, and a dialect would exclude most of them.
 *  - Interface terms follow the vocabulary Arabic software actually uses
 *    (لوحة التحكم, تسجيل الدخول, الإعدادات) rather than literal renderings,
 *    because a literal translation of a button is not a button anyone
 *    recognises.
 *
 * Product names are left in Latin script on purpose: PayPal, Stripe, Vimeo and
 * SMTP are searched and configured under those names, and transliterating them
 * makes a settings field harder to use, not easier.
 */
